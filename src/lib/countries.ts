type ApiCountry = {
  cca2?: string;
  name?: { common?: string };
};

function normalize(list: CountryOption[]) {
  const map = new Map<string, CountryOption>();
  for (const item of list) {
    const code = item.code.trim().toUpperCase();
    const name = item.name.trim();
    if (code.length !== 2 || !name) continue;
    map.set(code, { code, name });
  }
  return Array.from(map.values()).sort((a, b) => a.name.localeCompare(b.name));
}

function readCache(): CountryOption[] | null {
  if (typeof window === "undefined") return null;
  try {
    const raw = window.localStorage.getItem(CACHE_KEY);
    if (!raw) return null;
    const parsed = JSON.parse(raw) as CountryOption[];
    if (!Array.isArray(parsed) || parsed.length < 50) return null;
    return normalize(parsed);
  } catch {
    return null;
  }
}

function writeCache(list: CountryOption[]) {
  if (typeof window === "undefined") return;
  try {
    window.localStorage.setItem(CACHE_KEY, JSON.stringify(list));
  } catch {
    // ignore quota errors
  }
}

/** Fetch all world countries from Rest Countries API (with local cache + fallback). */
export async function fetchWorldCountries(): Promise<CountryOption[]> {
  const cached = readCache();
  if (cached) {
    // Refresh in background
    void refreshFromApi().catch(() => null);
    return cached;
  }

  try {
    return await refreshFromApi();
  } catch {
    return normalize(FALLBACK_COUNTRIES);
  }
}

async function refreshFromApi(): Promise<CountryOption[]> {
  const res = await fetch(
    "https://restcountries.com/v3.1/all?fields=name,cca2",
  );
  if (!res.ok) throw new Error(`Countries API ${res.status}`);
  const data = (await res.json()) as ApiCountry[];
  const list = normalize(
    data.map((item) => ({
      code: item.cca2 ?? "",
      name: item.name?.common ?? "",
    })),
  );
  if (list.length < 50) throw new Error("Incomplete countries payload");
  writeCache(list);
  return list;
}

export function getCachedCountries(): CountryOption[] {
  return readCache() ?? normalize(FALLBACK_COUNTRIES);
}

export function findCountryName(code: string): string | null {
  const upper = code.toUpperCase();
  const hit = getCachedCountries().find((c) => c.code === upper);
  return hit?.name ?? null;
}
